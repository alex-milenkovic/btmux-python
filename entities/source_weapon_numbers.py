def source_weapon(number):
    from entities.weapon import get_weapon
    if number < 0 or number >= len(SOURCE_WEAPON_NAMES):
        raise ValueError("undefined source weapon index")
    weapon=get_weapon(SOURCE_WEAPON_NAMES[number])
    if weapon is None:
        raise ValueError("source weapon metadata is unavailable")
    return weapon
